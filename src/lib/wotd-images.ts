/* ============================================================
   Word-of-the-day images — server-side filesystem helpers.

   Uploaded images live in `public/wotd/<wordId>.<ext>` and are
   exposed through the generated manifest in
   `src/lib/wotd-image-manifest.ts`.

   IMPORTANT: server-only (uses node:fs). Never import from a
   client component. Writing to `public/` works when the app runs
   on a normal filesystem (local dev / self-hosted); on serverless
   platforms the filesystem is read-only, so uploads are meant to
   be committed to the repo and deployed.
   ============================================================ */
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";

export const WOTD_DIR = path.join(process.cwd(), "public", "wotd");
export const WOTD_MANIFEST_PATH = path.join(
  process.cwd(),
  "src",
  "lib",
  "wotd-image-manifest.ts",
);

/** Accepted on-disk formats, best first (used to pick a preview). */
const EXTENSIONS = ["avif", "webp", "png", "jpg", "jpeg"];

function extOf(name: string): string {
  return path.extname(name).replace(".", "").toLowerCase();
}

/** Map every `public/wotd/<id>.<ext>` file to its public URL. */
export async function scanWotdImages(): Promise<Record<string, string>> {
  let entries: string[];
  try {
    entries = await readdir(WOTD_DIR);
  } catch {
    return {};
  }

  const picked = new Map<string, { rank: number; file: string }>();
  for (const name of entries) {
    const ext = extOf(name);
    const rank = EXTENSIONS.indexOf(ext);
    if (rank < 0) continue;
    const id = name.slice(0, name.length - ext.length - 1);
    const current = picked.get(id);
    if (!current || rank < current.rank) picked.set(id, { rank, file: name });
  }

  const map: Record<string, string> = {};
  for (const [id, { file }] of picked) map[id] = `/wotd/${file}`;
  return map;
}

/** Regenerate the committed manifest module from the directory. */
export async function writeWotdManifest(): Promise<Record<string, string>> {
  const map = await scanWotdImages();
  const entries = Object.entries(map)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([id, url]) => `  ${JSON.stringify(id)}: ${JSON.stringify(url)},`)
    .join("\n");

  const source = `/* AUTO-GENERATED by the admin panel (/admin) — do not edit by hand.
   Rebuild with: npm run gen:wotd */

export const WOTD_IMAGE: Record<string, string> = {
${entries}
};

export function wotdImageUrl(id: string): string | null {
  return WOTD_IMAGE[id] ?? null;
}
`;

  await mkdir(path.dirname(WOTD_MANIFEST_PATH), { recursive: true });
  await writeFile(WOTD_MANIFEST_PATH, source, "utf8");
  return map;
}

async function filesForId(id: string): Promise<string[]> {
  const entries = await readdir(WOTD_DIR).catch(() => [] as string[]);
  return entries.filter(
    (name) => name.startsWith(`${id}.`) && EXTENSIONS.includes(extOf(name)),
  );
}

/** Store a converted image for a word (always webp), replacing any prior file. */
export async function writeWotdImage(id: string, data: Buffer): Promise<string> {
  await mkdir(WOTD_DIR, { recursive: true });
  await Promise.all(
    (await filesForId(id)).map((name) => rm(path.join(WOTD_DIR, name), { force: true })),
  );
  await writeFile(path.join(WOTD_DIR, `${id}.webp`), data);
  return `/wotd/${id}.webp`;
}

/** Remove every stored image for a word. */
export async function removeWotdImage(id: string): Promise<void> {
  await Promise.all(
    (await filesForId(id)).map((name) => rm(path.join(WOTD_DIR, name), { force: true })),
  );
}
