/* ============================================================
   KanjiVG offline bundle — server-side filesystem helpers.

   Drop KanjiVG stroke files in `public/kanjivg/<5-hex>.svg`
   (e.g. `05c71.svg` for 山, `06d77.svg` for 海) and regenerate the
   manifest with `npm run gen:kanjivg`. Characters that are bundled
   are read from the app origin, so stroke practice works fully
   offline and never touches the CDN.

   KanjiVG © Ulrich Apel — CC-BY-SA 3.0 (https://kanjivg.tagaini.net).

   IMPORTANT: server-only (uses node:fs). Never import from a client
   component.
   ============================================================ */
import { mkdir, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

export const KANJIVG_DIR = path.join(process.cwd(), "public", "kanjivg");
export const KANJIVG_MANIFEST_PATH = path.join(
  process.cwd(),
  "src",
  "lib",
  "kanjivg-local-manifest.ts",
);

/** KanjiVG filenames are 5-digit lowercase hex codepoints. */
const HEX_RE = /^[0-9a-f]{5}$/;

/** Map every `public/kanjivg/<5-hex>.svg` file to its public URL. */
export async function scanKanjivgLocal(): Promise<Record<string, string>> {
  let entries: string[];
  try {
    entries = await readdir(KANJIVG_DIR);
  } catch {
    return {};
  }

  const map: Record<string, string> = {};
  for (const name of entries) {
    if (path.extname(name).toLowerCase() !== ".svg") continue;
    const hex = path.basename(name, path.extname(name)).toLowerCase();
    if (!HEX_RE.test(hex)) continue;
    map[hex] = `/kanjivg/${name}`;
  }
  return map;
}

/** Regenerate the committed manifest module from the directory. */
export async function writeKanjivgManifest(): Promise<Record<string, string>> {
  const map = await scanKanjivgLocal();
  const entries = Object.entries(map)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([hex, url]) => `  ${JSON.stringify(hex)}: ${JSON.stringify(url)},`)
    .join("\n");

  const source = `/* AUTO-GENERATED by scripts/gen-kanjivg.mjs — do not edit by hand.
   Bundled offline KanjiVG strokes from public/kanjivg.
   Rebuild with: npm run gen:kanjivg */

export const KANJIVG_LOCAL: Record<string, string> = {
${entries}
};

/** Public URL of a bundled stroke file for a 5-digit hex code, if present. */
export function kanjivgLocalUrl(hex: string): string | null {
  return KANJIVG_LOCAL[hex.toLowerCase()] ?? null;
}
`;

  await mkdir(path.dirname(KANJIVG_MANIFEST_PATH), { recursive: true });
  await writeFile(KANJIVG_MANIFEST_PATH, source, "utf8");
  return map;
}
