/* ============================================================
   Generates the ja-JP MP3s that cover the screens with no
   pre-recorded audio (Radical Confluence + Syntax Scramble),
   and re-emits src/lib/japanese-audio-manifest.ts from that
   exact clip list.

   Requirements: `edge-tts` (pip) and `ffmpeg` on PATH.
   Voice override: TTS_VOICE=ja-JP-KeitaNeural node scripts/gen-audio.mjs

   Run from the repo root:  node scripts/gen-audio.mjs
   ============================================================ */
import { spawn } from "node:child_process";
import { mkdir, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { RADICAL_TOKENS } from "../src/lib/radical-flood.ts";
import { SYNTAX_SCRAMBLE_TASKS } from "../src/data/syntax-scramble.seed.ts";

const VOICE = process.env.TTS_VOICE ?? "ja-JP-NanamiNeural";
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const TMP = path.join(os.tmpdir(), "nihongo-gen");

function unique(values) {
  return [...new Set(values)];
}

function buildClips() {
  const clips = [];

  unique(RADICAL_TOKENS.map((token) => token.reading)).forEach((text, index) => {
    clips.push({ text, url: `/audio/radicals/r-${index + 1}.mp3` });
  });

  unique(
    SYNTAX_SCRAMBLE_TASKS.flatMap((task) => task.parts.map((part) => part.reading)),
  ).forEach((text, index) => {
    clips.push({ text, url: `/audio/scramble/p-${index + 1}.mp3` });
  });

  unique(SYNTAX_SCRAMBLE_TASKS.map((task) => task.fullJapanese)).forEach(
    (text, index) => {
      clips.push({ text, url: `/audio/scramble/s-${index + 1}.mp3` });
    },
  );

  const seen = new Map();
  for (const clip of clips) {
    if (seen.has(clip.text)) {
      throw new Error(`duplicate clip text: ${clip.text} (${seen.get(clip.text)} / ${clip.url})`);
    }
    seen.set(clip.text, clip.url);
  }
  return clips;
}

function run(command, args) {
  return new Promise((resolve, reject) => {
    const child = spawn(command, args, { stdio: ["ignore", "pipe", "pipe"] });
    let stderr = "";
    child.stdout.on("data", () => {});
    child.stderr.on("data", (chunk) => {
      stderr += chunk.toString();
    });
    child.on("error", reject);
    child.on("close", (code) => {
      if (code === 0) resolve();
      else reject(new Error(`${command} exited ${code}\n${stderr}`));
    });
  });
}

async function synth(clip, index) {
  const raw = path.join(TMP, `raw-${index}.mp3`);
  const textFile = path.join(TMP, `text-${index}.txt`);
  const out = path.join(ROOT, "public", clip.url.slice(1));

  await mkdir(path.dirname(out), { recursive: true });
  await writeFile(textFile, `${clip.text}\n`, "utf8");
  await run("edge-tts", [
    "--voice",
    VOICE,
    "--file",
    textFile,
    "--write-media",
    raw,
  ]);
  await run("ffmpeg", [
    "-y",
    "-hide_banner",
    "-loglevel",
    "error",
    "-i",
    raw,
    "-map_metadata",
    "-1",
    "-id3v2_version",
    "0",
    "-write_id3v1",
    "0",
    "-write_xing",
    "0",
    "-ar",
    "24000",
    "-ac",
    "1",
    "-b:a",
    "64k",
    out,
  ]);

  return { text: clip.text, url: clip.url };
}

function manifestSource(entries) {
  const body = entries
    .map((entry) => `  ${JSON.stringify(entry.text)}: ${JSON.stringify(entry.url)},`)
    .join("\n");
  return `/* ============================================================
   AUTO-GENERATED by scripts/gen-audio.mjs — do not edit by hand.
   Phrase audio shipped with the app for the screens that have no
   other recording (radicals + Syntax Scramble). Voice: ${VOICE}.
   Regenerate with: node scripts/gen-audio.mjs
   ============================================================ */

export const PHRASE_AUDIO: Record<string, string> = {
${body}
};

/** MP3 for an exact Japanese phrase (kana reading or full sentence), if shipped. */
export function phraseAudioUrl(text: string | null | undefined): string | null {
  if (!text) return null;
  return PHRASE_AUDIO[text] ?? null;
}
`;
}

async function main() {
  const clips = buildClips();
  await mkdir(TMP, { recursive: true });
  console.log(`voice=${VOICE} clips=${clips.length}`);

  const entries = [];
  for (const [index, clip] of clips.entries()) {
    process.stdout.write(`[${index + 1}/${clips.length}] ${clip.text} -> ${clip.url}\n`);
    entries.push(await synth(clip, index));
  }

  await writeFile(
    path.join(ROOT, "src", "lib", "japanese-audio-manifest.ts"),
    manifestSource(entries),
    "utf8",
  );
  await rm(TMP, { recursive: true, force: true });
  console.log(`wrote ${entries.length} files + src/lib/japanese-audio-manifest.ts`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
